let currentLocale: Locale = 'mr';

export function setLocale(locale: Locale) {
  currentLocale = locale;
  if (typeof window !== 'undefined') {
    localStorage.setItem('locale', locale);
  }
}

export function getLocale(): Locale {
  if (typeof window !== 'undefined') {
    const stored = localStorage.getItem('locale') as Locale;
    if (stored) currentLocale = stored;
  }
  return currentLocale;
}

export function t(key: string): string {
  return translations[currentLocale]?.[key] || translations.en[key] || key;
}

export function formatDate(date: Date | string): string {
  const d = typeof date === 'string' ? new Date(date) : date;
  const day = String(d.getDate()).padStart(2, '0');
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const year = d.getFullYear();
  return `${day}-${month}-${year}`;
}

export function formatCurrency(amount: number | string | null | undefined): string {
  const num = typeof amount === 'string' ? parseFloat(amount) : amount || 0;
  return `₹${num.toLocaleString('en-IN', { minimumFractionDigits: 0, maximumFractionDigits: 2 })}`;
}

export function getWhatsAppShareText(workerName: string, month: string, present: number, wage: number, advance: number, paid: number, balance: number): string {
  const t2 = (key: string) => translations.mr[key] || key;
  return `${t2('appName')}\n\n${t2('workers')}: ${workerName}\nमहिना: ${month}\n\nकामाचे दिवस: ${present}\nमजुरी: ${formatCurrency(wage)}\nउचल: ${formatCurrency(advance)}\nदिलेली रक्कम: ${formatCurrency(paid)}\n\nबाकी: ${formatCurrency(balance)}`;
}

// Work type presets - used by workers forms + list/detail display
export const WORK_TYPE_PRESETS = [
  { value: 'Painting', labelKey: 'workTypePainting' },
  { value: 'Masonry', labelKey: 'workTypeMasonry' },
  { value: 'Carpentry', labelKey: 'workTypeCarpentry' },
  { value: 'Electrical', labelKey: 'workTypeElectrical' },
  { value: 'Plumbing', labelKey: 'workTypePlumbing' },
  { value: 'Helper', labelKey: 'workTypeHelper' },
  { value: 'Other', labelKey: 'workTypeOther' },
] as const;

export function getWorkTypeLabel(workType: string | null | undefined): string {
  if (!workType) return '-';
  const preset = WORK_TYPE_PRESETS.find((p) => p.value.toLowerCase() === workType.toLowerCase());
  if (preset) return t(preset.labelKey);
  return workType;
}

